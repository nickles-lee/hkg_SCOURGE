/* ----------------------------- trace (bounded) ----------------------------- */
static void cprg_trace(const char *msg)
{
    if (access(CPRG_TRACE_FILE, F_OK) != 0) return;
    int fd = open(CPRG_TRACE_LOG, O_WRONLY | O_CREAT | O_APPEND, 0644);
    if (fd < 0) return;
    char line[192];
    int n = snprintf(line, sizeof line, "%s\n", msg);
    if (n > 0) {
        size_t w = (size_t)n;
        if (w > sizeof line - 1) w = sizeof line - 1;
        ssize_t wr = write(fd, line, w);
        (void)wr;
    }
    (void)close(fd);
}

static void cprg_trace2(const char *tag, unsigned long a, unsigned long b)
{
    char line[192];
    int n = snprintf(line, sizeof line, "%s 0x%lx 0x%lx", tag, a, b);
    if (n > 0) cprg_trace(line);
}
#endif /* !CP_RG_UNIT_TEST */

/* ------------------------- wrapper / real P pointer ------------------------ */
typedef void (*cprg_p_fn)(void *, int, int, void *, void *, void *);

#ifdef CP_RG_UNIT_TEST
/* Compile-time hook: tests/test_cp_rg_wrapper.c defines this fake P. */
extern cprg_p_fn cp_rg_test_real_p;
#define CPRG_REAL_P cp_rg_test_real_p
#else
static cprg_p_fn cprg_real_p;
#define CPRG_REAL_P cprg_real_p
#endif

/* Exact signature/calling convention of the stock function at 0x1cf4a.
 * Returns void (0x1d09d/0x1d09e: leave; ret, no value set). */
void cp_rg_p_wrapper(void *buf, int len, int paramId,
                     void *vecIds, void *vecPtrs, void *vecLens)
{
    cprg_p_fn real_p = CPRG_REAL_P;
    if (!real_p) return;                       /* fail-open */

    if (paramId != 6 && paramId != 7) {
        real_p(buf, len, paramId, vecIds, vecPtrs, vecLens);
        return;
    }
    if (len < 0 || (size_t)len > CPRG_TMP_CAP) {
        real_p(buf, len, paramId, vecIds, vecPtrs, vecLens);
        return;
    }

    /* Copy the original bytes and append the BE16 message IDs. P copies the
     * buffer before returning (0x1cfee new[], 0x1d03d memcpy, 0x1d059 stores the
     * copy), so stack storage is safe; bound it in all cases. */
    unsigned char tmp[CPRG_TMP_CAP];
    const unsigned short *ids = (paramId == 6) ? CP_RG_SENT_IDS : CP_RG_RECV_IDS;
    size_t nids = (paramId == 6) ? 2u : 3u;
    size_t n = cp_rg_append_ids(tmp, sizeof tmp, buf, (size_t)len, ids, nids);
    if (n == 0) {                              /* any doubt -> stock behaviour */
        real_p(buf, len, paramId, vecIds, vecPtrs, vecLens);
        return;
    }
    real_p(tmp, (int)n, paramId, vecIds, vecPtrs, vecLens);

    if (paramId == 7) {
        /* One extra (id, ptr, len) triple: Identification parameter 30,
         * RouteGuidanceDisplayComponent (values from CP_DESIGN.md §6b / DiPlay). */
        unsigned char comp[CPRG_COMP_CAP];
        size_t cn = cp_rg_build_component(comp, sizeof comp);
        if (cn != 0) { real_p(comp, (int)cn, 30, vecIds, vecPtrs, vecLens); cp_rg_ident_patched = 1; }
    }
}

