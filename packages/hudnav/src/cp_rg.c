/* ------------- receive dispatcher wrapper (0x13afa), send + receive plumbing ------------- */
typedef void (*cprg_disp_fn)(void *, void *, const unsigned char *, int, int, int);
static cprg_disp_fn cprg_real_disp;
static cp_rg_send_ctx cprg_send;
static cp_rg_vendor cprg_vendor;

/* Same arguments and calling convention as the stock handleReceivedData (rdi=this, rsi, rdx=data, ecx=len,
 * r8=?, r9=link session). Route-guidance messages are handed to the receiver BEFORE the stock handler runs
 * (stock only logs unknown ids and returns); the 0x5200 send happens AFTER the stock handler, in the same
 * context the stock replies use. */
void cp_rg_dispatch_wrapper(void *self, void *a1, const unsigned char *d, int n, int r8, int session)
{
    cprg_disp_fn real = cprg_real_disp;
    if (!real) return;
    int id = cp_rg_msg_id(d, n);
    if (id == 0x5201 || id == 0x5202 || id == 0x5204) cp_rx_feed_message(session, d, n);
    real(self, a1, d, n, r8, session);
    cprg_send.ident_patched = cp_rg_ident_patched;
    if (cp_rg_after_dispatch(&cprg_send, self, d, n, session)) cprg_trace("CPRG sent 0x5200");
}

/* ------------------------- runtime patch machinery ------------------------ */
struct base_ctx { uintptr_t base; int found; };

static int cprg_base_cb(struct dl_phdr_info *info, size_t size, void *arg)
{
    struct base_ctx *c = (struct base_ctx *)arg;
    (void)size;
    /* The main PIE executable is the entry with an empty name (or its path);
     * require a PT_LOAD at vaddr 0 so a same-named DSO cannot be mistaken for it. */
    if (info->dlpi_name && info->dlpi_name[0] != '\0' &&
        strcmp(info->dlpi_name, "/" CPRG_EXE) != 0 &&
        strstr(info->dlpi_name, "/" CPRG_EXE) == NULL) return 0;
    int has_zero = 0;
    for (int i = 0; i < info->dlpi_phnum; i++) {
        if (info->dlpi_phdr[i].p_type == PT_LOAD && info->dlpi_phdr[i].p_vaddr == 0)
            has_zero = 1;
    }
    if (!has_zero) return 0;
    c->base = (uintptr_t)info->dlpi_addr;
    c->found = 1;
    return 1;
}

static int cprg_find_base(uintptr_t *base)
{
    struct base_ctx c;
    memset(&c, 0, sizeof c);
    dl_iterate_phdr(cprg_base_cb, &c);
    if (c.found) *base = c.base;
    return c.found;
}

static int cprg_rel32_ok(uintptr_t from, uintptr_t to)
{
    int64_t d = (int64_t)to - (int64_t)(from + 5);
    return d >= (int64_t)INT32_MIN && d <= (int64_t)INT32_MAX;
}

/* Write 5 bytes under RW|X, then restore R|X. Handles a call crossing a page. */
static int cprg_write5(uintptr_t site, const unsigned char bytes[5])
{
    uintptr_t ps = site & ~((uintptr_t)4095);
    uintptr_t pe = (site + 5 + 4095) & ~((uintptr_t)4095);
    size_t span = (size_t)(pe - ps);
    if (mprotect((void *)ps, span, PROT_READ | PROT_WRITE | PROT_EXEC) != 0) return 0;
    memcpy((void *)site, bytes, 5);
    if (mprotect((void *)ps, span, PROT_READ | PROT_EXEC) != 0) {
        (void)mprotect((void *)ps, span, PROT_READ | PROT_EXEC); /* best effort retry */
        return 0;
    }
    return 1;
}

static int cprg_patch_call(uintptr_t site, uintptr_t thunk)
{
    unsigned char insn[5];
    int32_t rel = (int32_t)((int64_t)thunk - (int64_t)(site + 5));
    insn[0] = 0xe8;
    insn[1] = (unsigned char)(rel & 0xff);
    insn[2] = (unsigned char)((rel >> 8) & 0xff);
    insn[3] = (unsigned char)((rel >> 16) & 0xff);
    insn[4] = (unsigned char)((rel >> 24) & 0xff);
    return cprg_write5(site, insn);
}

/* One anonymous page, final protection R|X, within rel32 range of all three sites.
 * Thunk i (12 bytes each): movabs rax, <wrapper[i]>; jmp rax. */
#define CPRG_NSITES 3
static void *cprg_map_thunks(uintptr_t base, const uintptr_t site[CPRG_NSITES],
                             const uintptr_t wrapper[CPRG_NSITES], uintptr_t thunk[CPRG_NSITES])
{
    static const int64_t hints[] = {
        -0x200000LL, -0x1000000LL, -0x10000000LL, -0x20000000LL,
         0x200000LL,  0x1000000LL,  0x10000000LL,  0x20000000LL, 0LL
    };
    for (unsigned i = 0; i < sizeof hints / sizeof hints[0]; i++) {
        int64_t h = (int64_t)base + hints[i];
        if (h < 0) continue;
        void *p = mmap((void *)(uintptr_t)h, 4096, PROT_READ | PROT_WRITE,
                       MAP_PRIVATE | MAP_ANONYMOUS, -1, 0);
        if (p == MAP_FAILED) continue;
        uintptr_t a = (uintptr_t)p;
        int ok = 1;
        for (int k = 0; k < CPRG_NSITES; k++)
            if (!cprg_rel32_ok(site[k], a + 12u * (unsigned)k)) ok = 0;
        if (!ok) { (void)munmap(p, 4096); continue; }
        for (int k = 0; k < CPRG_NSITES; k++) {
            unsigned char thunk_code[12];
            uint64_t w = (uint64_t)wrapper[k];
            thunk_code[0] = 0x48; thunk_code[1] = 0xb8;
            for (int j = 0; j < 8; j++) thunk_code[2 + j] = (unsigned char)((w >> (8 * j)) & 0xff);
            thunk_code[10] = 0xff; thunk_code[11] = 0xe0;
            memcpy((void *)(a + 12u * (unsigned)k), thunk_code, 12);
            thunk[k] = a + 12u * (unsigned)k;
        }
        if (mprotect(p, 4096, PROT_READ | PROT_EXEC) != 0) {
            (void)munmap(p, 4096);
            continue;
        }
        return p;
    }
    return NULL;
}

__attribute__((constructor)) static void cprg_init(void)
{
    char exe[256];
    ssize_t n = readlink("/proc/self/exe", exe, sizeof exe - 1);
    if (n <= 0 || n >= (ssize_t)sizeof exe) return;
    exe[n] = '\0';
    const char *bn = strrchr(exe, '/');
    bn = bn ? bn + 1 : exe;
    if (strcmp(bn, CPRG_EXE) != 0) return;
    if (access(CPRG_ENABLE_FILE, F_OK) != 0) return;  /* gate: off by default */

    cprg_trace("CPRG gate on");

    uintptr_t base = 0;
    if (!cprg_find_base(&base)) { cprg_trace("CPRG no executable base"); return; }
    unsigned char hdr[4] = { 0x7f, 'E', 'L', 'F' };
    if (memcmp((void *)base, hdr, sizeof hdr) != 0) { cprg_trace("CPRG bad ELF header"); return; }

    uintptr_t site1 = base + CPRG_SITE1_OFF, site2 = base + CPRG_SITE2_OFF;
    uintptr_t pp = base + CPRG_P_OFF;
    unsigned char got[CPRG_SITE_BYTES];
    memcpy(got, (void *)site1, CPRG_SITE_BYTES);
    if (memcmp(got, cprg_site1_fp, CPRG_SITE_BYTES) != 0) {
        cprg_trace("CPRG fingerprint mismatch site1; no action");
        return;
    }
    memcpy(got, (void *)site2, CPRG_SITE_BYTES);
    if (memcmp(got, cprg_site2_fp, CPRG_SITE_BYTES) != 0) {
        cprg_trace("CPRG fingerprint mismatch site2; no action");
        return;
    }
    if (memcmp((void *)pp, cprg_p_fp, sizeof cprg_p_fp) != 0) {
        cprg_trace("CPRG fingerprint mismatch P; no action");
        return;
    }
    int32_t r1, r2;
    memcpy(&r1, (void *)(site1 + 1), 4);
    memcpy(&r2, (void *)(site2 + 1), 4);
    if ((uintptr_t)((int64_t)site1 + 5 + r1) != pp ||
        (uintptr_t)((int64_t)site2 + 5 + r2) != pp) {
        cprg_trace("CPRG rel32 target mismatch; no action");
        return;
    }

    uintptr_t site3 = base + CPRG_SITE3_OFF;
    memcpy(got, (void *)site3, CPRG_SITE_BYTES);
    if (memcmp(got, cprg_site3_fp, CPRG_SITE_BYTES) != 0) {
        cprg_trace("CPRG fingerprint mismatch site3 (dispatcher call); no action");
        return;
    }
    int32_t r3;
    memcpy(&r3, (void *)(site3 + 1), 4);
    if ((uintptr_t)((int64_t)site3 + 5 + r3) != base + CPRG_DISP_OFF) {
        cprg_trace("CPRG rel32 target mismatch site3; no action");
        return;
    }

    char line[192];
    (void)snprintf(line, sizeof line, "CPRG fingerprint OK base=0x%lx P=0x%lx",
                   (unsigned long)base, (unsigned long)pp);
    cprg_trace(line);

    const uintptr_t sites[CPRG_NSITES] = { site1, site2, site3 };
    const uintptr_t wrappers[CPRG_NSITES] = { (uintptr_t)&cp_rg_p_wrapper, (uintptr_t)&cp_rg_p_wrapper,
                                              (uintptr_t)&cp_rg_dispatch_wrapper };
    uintptr_t th[CPRG_NSITES];
    void *page = cprg_map_thunks(base, sites, wrappers, th);
    if (!page) { cprg_trace("CPRG no in-range thunk page; no action"); return; }
    cprg_trace2("CPRG thunks page/wrapper", (unsigned long)page, (unsigned long)wrappers[0]);
    (void)snprintf(line, sizeof line, "CPRG thunk1=0x%lx thunk2=0x%lx thunk3=0x%lx",
                   (unsigned long)th[0], (unsigned long)th[1], (unsigned long)th[2]);
    cprg_trace(line);

    /* Vendor table for the 0x5200 send (sequence of the stock sender 0x204e6, docs/hudnav/CP_PROTOCOL.md). */
    cprg_vendor.encode   = (int (*)(int, int, void *, void *, void *, unsigned char **))(base + CPRG_ENC_OFF);
    cprg_vendor.pkt_ctor = (void (*)(void *, const unsigned char *, int))(base + CPRG_PKTC_OFF);
    cprg_vendor.send     = (long (*)(void *, void *, int, int))(base + CPRG_SEND_OFF);
    cprg_vendor.pkt_dtor = (void (*)(void *))(base + CPRG_PKTD_OFF);
    cprg_vendor.free_arr = (void (*)(void *))(base + CPRG_DELARR_OFF);
    cp_rg_send_init(&cprg_send, &cprg_vendor);
    cprg_send.with_component_id = (access("/rw_data/hudnav/cp-rg-with-id", F_OK) == 0);
    cprg_real_disp = (cprg_disp_fn)(base + CPRG_DISP_OFF);

    /* Install the real-P pointer before the first patched call can execute. */
    cprg_real_p = (cprg_p_fn)pp;

    unsigned char orig1[5], orig2[5];
    memcpy(orig1, (void *)site1, 5);
    memcpy(orig2, (void *)site2, 5);
    if (!cprg_patch_call(site1, th[0])) {
        cprg_trace("CPRG patch site1 failed; no action");
        cprg_real_p = NULL; cprg_real_disp = NULL;
        return;
    }
    if (!cprg_patch_call(site2, th[1])) {
        (void)cprg_write5(site1, orig1);   /* undo the partial patch */
        cprg_real_p = NULL; cprg_real_disp = NULL;
        cprg_trace("CPRG patch site2 failed; rolled back");
        return;
    }
    if (!cprg_patch_call(site3, th[2])) {  /* identification lists without send/receive are pointless: stock */
        (void)cprg_write5(site1, orig1);
        (void)cprg_write5(site2, orig2);
        cprg_real_p = NULL; cprg_real_disp = NULL;
        cprg_trace("CPRG patch site3 failed; rolled back all");
        return;
    }
    cprg_trace2("CPRG patched sites", (unsigned long)site1, (unsigned long)site2);
    cprg_trace2("CPRG patched dispatcher site", (unsigned long)site3, 0);
}

